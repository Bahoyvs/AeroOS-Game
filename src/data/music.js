/**
 * Music data — the songbook (audio overhaul, replaces the single generative
 * arpeggio in ui/audio.js).
 *
 * Pure data. No WebAudio, no `window`, no timers: this file must stay
 * importable from plain Node so the tracks can be unit-tested (bar counts,
 * chord validity, playlist coverage) without a browser. The synthesis that
 * turns this into sound lives in `src/ui/music.js`.
 *
 * ── Notation ────────────────────────────────────────────────────────────────
 * A bar is 4/4 divided into 16 steps (16th notes).
 *
 *   root        Song key, in semitones from A4 (440 Hz). 0 = A4, 3 = C5, 5 = D5.
 *               Melodies are written to sit roughly 400–1000 Hz; the engine
 *               transposes each part by `octaves` from there.
 *
 *   chords      One entry per bar: [chordType, semitonesFromSongRoot].
 *               A section with 4 chords and `bars: 8` simply loops them.
 *
 *   drums       Per-lane 16-character patterns:
 *                 'x' hit    '.' ghost (soft hit)    '-' rest
 *               A lane may also be an array of patterns — one per bar, cycled,
 *               which is how fills and section-opening crashes are written.
 *
 *   bass/arp    [step, semitonesFromCurrentChordRoot, durationInSteps]
 *               `step` is counted from the start of the *section*, so a phrase
 *               can run across bar lines. Offsets are semitones (0 = root,
 *               7 = fifth, 12 = octave up, -12 = octave down).
 *
 *   lead        [step, scaleDegree, durationInSteps]
 *               Degrees index the song's `scale`; degrees past the end of the
 *               scale wrap into the next octave (7 = root + 1 octave for a
 *               7-note scale), negative degrees wrap downwards.
 *
 *   fx          [step, effectName] — 'riser', 'downlifter', 'impact', 'noise'.
 *
 * Everything is optional. A section with only `chords` and `pad: true` is a
 * legitimate 4-bar breakdown.
 */

